export const LANGS = [['es', 'ES', 'Español'], ['en', 'EN', 'English'], ['pt', 'PT', 'Português (BR)']];
const LOCALE = { es: 'es', en: 'en', pt: 'pt-BR' };

function detect() {
  try { const s = localStorage.getItem('prh-lang'); if (s && D[s]) return s; } catch { /* storage blocked */ }
  const n = (navigator.language || 'es').toLowerCase();
  return n.startsWith('pt') ? 'pt' : n.startsWith('en') ? 'en' : 'es';
}
let lang = detect();

export const getLang = () => lang;
export function setLang(l) {
  if (!D[l]) return;
  lang = l;
  try { localStorage.setItem('prh-lang', l); } catch { /* ignore */ }
  document.documentElement.lang = LOCALE[l];
}
export function t(key, params) {
  let s = D[lang][key] ?? D.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export const num = (n, opts) => n.toLocaleString(LOCALE[lang], opts);

/** Translate static markup: data-i18n (text), data-i18n-title, data-i18n-aria. */
export function applyStatic(root = document) {
  document.documentElement.lang = LOCALE[lang];
  root.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((e) => { e.title = t(e.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((e) => { e.setAttribute('aria-label', t(e.dataset.i18nAria)); });
}
